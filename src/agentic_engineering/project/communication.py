"""Shared writing guidance for project instructions and agent prompts."""

WRITING_RULES = (
    "Use plain, concise language in conversations, commits, PRs, reviews, plans, specs, and docs. "
    "Lead with the outcome. Give the facts needed to understand or act. "
    "Explain necessary technical terms once, where they first matter. "
    "For a review finding, state the problem, its consequence, and the file and line. "
    "Preserve uncertainty, requirement strength, exact names, commands, and safety conditions. "
    "Keep prerequisites before the actions they govern."
)
